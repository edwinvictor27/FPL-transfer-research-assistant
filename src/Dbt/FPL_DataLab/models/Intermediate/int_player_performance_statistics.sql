SELECT
    id AS player_id,
    team AS team_id,
    first_name AS player_first_name,
    second_name AS player_last_name,
    web_name AS player_display_name,
    team_code AS team_code,
    minutes AS total_minutes_played,
    starts AS total_starts,
    total_points AS total_fpl_points,
    points_per_game AS average_fpl_points_per_game,
    goals_scored AS total_goals_scored,
    assists AS total_assists,
    clean_sheets AS total_clean_sheets,
    goals_conceded AS total_goals_conceded,
    saves AS total_saves,
    bonus AS total_bonus_points,
    bps AS total_bonus_points_system_score,
    yellow_cards AS total_yellow_cards,
    red_cards AS total_red_cards,
    penalties_saved AS total_penalties_saved,
    penalties_missed AS total_penalties_missed
FROM {{ ref('stg_fpl_player_data') }}